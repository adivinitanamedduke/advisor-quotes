using System.Text.Json;
using Business.Abstractions.Domain.Quotes;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.ChangeTracking;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace Data.SQL.EF.Configurations
{
    public class QuoteConfiguration : IEntityTypeConfiguration<Quote>
    {
        public void Configure(EntityTypeBuilder<Quote> builder)
        {
            builder.ToTable("quotes");
            builder.HasKey(e => e.Id);

            builder.Property(e => e.Identifier).IsRequired();
            builder.HasIndex(e => e.Identifier).IsUnique();

            // QT-000123, generated by the database so it is gap tolerant but never duplicated
            builder.Property(e => e.Reference)
                .HasMaxLength(20)
                .HasDefaultValueSql($"'QT-' || lpad(nextval('{QuotesDbContext.ReferenceSequence}')::text, 6, '0')")
                .ValueGeneratedOnAdd();
            builder.HasIndex(e => e.Reference).IsUnique();

            builder.Property(e => e.AdviserId).HasMaxLength(100).IsRequired();

            builder.Property(e => e.ClientFullName).HasMaxLength(200).IsRequired();
            builder.Property(e => e.ClientDateOfBirth).IsRequired();

            builder.Property(e => e.ProductCode).HasMaxLength(50).IsRequired();
            builder.Property(e => e.CoverAmount).HasPrecision(14, 2);
            builder.Property(e => e.MonthlyPremium).HasPrecision(12, 2);
            builder.Property(e => e.Currency).HasMaxLength(3).IsRequired();
            builder.Property(e => e.PricingVersion).HasMaxLength(20).IsRequired();

            builder.Property(e => e.RatingFactors)
                .HasColumnType("jsonb")
                .HasConversion(
                    v => JsonSerializer.Serialize(v, (JsonSerializerOptions?)null),
                    v => JsonSerializer.Deserialize<Dictionary<string, decimal>>(v, (JsonSerializerOptions?)null) ?? new(),
                    new ValueComparer<Dictionary<string, decimal>>(
                        (a, b) => a!.Count == b!.Count && !a.Except(b).Any(),
                        v => v.Aggregate(0, (hash, pair) => HashCode.Combine(hash, pair.Key, pair.Value)),
                        v => new Dictionary<string, decimal>(v)));

            builder.Property(e => e.Status).HasConversion<string>().HasMaxLength(20).IsRequired();
            builder.Property(e => e.Notes).HasMaxLength(2000);

            builder.Property(e => e.IdempotencyKey).HasMaxLength(100);
            builder.Property(e => e.RequestFingerprint).HasMaxLength(64).IsFixedLength().IsRequired();

            builder.Property(e => e.CreatedAt).IsRequired();
            builder.Property(e => e.UpdatedAt).IsRequired();

            // Maps to the Postgres xmin system column for optimistic concurrency
            builder.Property(e => e.Version).IsRowVersion();

            // An Idempotency-Key is unique per adviser; the database settles concurrent replays
            builder.HasIndex(e => new { e.AdviserId, e.IdempotencyKey })
                .IsUnique()
                .HasFilter("idempotency_key IS NOT NULL");

            // Duplicate window lookup and list screens
            builder.HasIndex(e => new { e.AdviserId, e.RequestFingerprint, e.CreatedAt });
            builder.HasIndex(e => new { e.AdviserId, e.Status, e.CreatedAt });

            builder.HasMany(e => e.StatusHistory)
                .WithOne()
                .HasForeignKey(e => e.QuoteId)
                .OnDelete(DeleteBehavior.Cascade);
        }
    }
}
